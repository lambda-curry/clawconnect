describe("buildSessionRows — session-first rows keyed by sessionKey", () => {
  it("collapses multiple tasks in the same session to one row, keeping the most recent", () => {
    const tasks = [
      task({ taskId: "t1", jobId: "t1", lastEventAt: 1000, status: "done" }),
      task({ taskId: "t2", jobId: "t2", lastEventAt: 2000, status: "running" }),
    ];
    const rows = buildSessionRows(tasks);
    expect(rows).toHaveLength(1);
    expect(rows[0].latestTask.taskId).toBe("t2");
  });

  it("sorts by recency, newest first, with the highlighted session pinned to the top", () => {
    const rows = buildSessionRows(
      [
        task({ sessionKey: "old", lastEventAt: 1000 }),
        task({ sessionKey: "new", lastEventAt: 5000 }),
        task({ sessionKey: "mounted", lastEventAt: 500 }),
      ],
      { highlightSessionKey: "mounted" },
    );
    expect(rows.map((r) => r.sessionKey)).toEqual(["mounted", "new", "old"]);
  });

  it("marks the highlighted row expanded by default; others unexpanded", () => {
    const rows = buildSessionRows([task({ sessionKey: "a" }), task({ sessionKey: "b" })], { highlightSessionKey: "a" });
    expect(rows.find((r) => r.sessionKey === "a")?.expanded).toBe(true);
    expect(rows.find((r) => r.sessionKey === "b")?.expanded).toBe(false);
  });
});

describe("filterRows — Active default view + Recent view, exact status preserved underneath", () => {
  const rows = buildSessionRows([
    task({ sessionKey: "a", status: "running", lastEventAt: 3000 }),
    task({ sessionKey: "b", status: "blocked", lastEventAt: 2000 }),
    task({ sessionKey: "c", status: "done", lastEventAt: 1000 }),
    task({ sessionKey: "d", status: "failed", lastEventAt: 500 }),
  ]);

  it('"active" view (default) shows only Active + Needs attention groups', () => {
    const active = filterRows(rows, "active");
    expect(active.map((r) => r.sessionKey).sort()).toEqual(["a", "b"]);
  });

  it('"recent" view shows every group, and the underlying task.status is untouched', () => {
    const recent = filterRows(rows, "recent");
    expect(recent).toHaveLength(4);
    expect(recent.find((r) => r.sessionKey === "d")?.latestTask.status).toBe("failed");
  });

  it("the pinned (focused/mounted) session always shows in Active view even once it's terminal — a finished task must not disappear the moment it completes", () => {
    const active = filterRows(rows, "active", "c"); // "c" is done — terminal, normally filtered
    expect(active.map((r) => r.sessionKey).sort()).toEqual(["a", "b", "c"]);
  });

  it("pinning a session that's already visible in Active view doesn't duplicate it", () => {
    const active = filterRows(rows, "active", "a"); // "a" is running — already visible
    expect(active.filter((r) => r.sessionKey === "a")).toHaveLength(1);
  });

  it("with no pinned session, behavior is unchanged from the two-argument call", () => {
    expect(filterRows(rows, "active")).toEqual(filterRows(rows, "active", undefined));
  });
});

