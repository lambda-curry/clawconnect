describe("groupStatus — display bucketing preserves exact status", () => {
  it("maps every TaskStatus to exactly one of the four human groups", () => {
    expect(groupStatus("running")).toBe("active");
    expect(groupStatus("queued")).toBe("active");
    expect(groupStatus("blocked")).toBe("needs_attention");
    expect(groupStatus("needs-human")).toBe("needs_attention");
    expect(groupStatus("done")).toBe("completed");
    expect(groupStatus("completed")).toBe("completed");
    expect(groupStatus("completed_no_summary")).toBe("completed");
    expect(groupStatus("failed")).toBe("failed");
  });

  it("keeps the exact completed get_task shape successful even after lifecycle:end", () => {
    const completed = task({
      status: "completed",
      isError: false,
      isTerminal: true,
      logs: [{ type: "lifecycle", text: "Agent lifecycle: end", ts: 2000 }],
    });
    expect(groupStatus(completed.status)).toBe("completed");
    expect(deriveStatusPill(groupStatus(completed.status))).toEqual({ icon: "✓", label: "Completed" });
  });

  it("grouping is a pure derived view — the underlying task object is never mutated", () => {
    const t = task({ status: "blocked" });
    const before = JSON.stringify(t);
    groupStatus(t.status);
    expect(JSON.stringify(t)).toBe(before);
    expect(t.status).toBe("blocked"); // exact status preserved, not rewritten to "needs_attention"
  });
});

describe("deriveTitle — generated by default, never from the prompt", () => {
  it("prefers a PR/branch label when artifacts have one", () => {
    expect(deriveTitle(task({ artifacts: { prUrl: "https://x/pull/1", branchName: "fix/thing" } }))).toBe("PR: fix/thing");
  });

  it("falls back to the agent reply summary, truncated", () => {
    expect(deriveTitle(task({ status: "done", summary: "Fixed the login bug and added tests." }))).toBe(
      "Fixed the login bug and added tests.",
    );
    const long = "x".repeat(100);
    expect(deriveTitle(task({ status: "done", summary: long }))).toHaveLength(64);
  });

  it("uses an agent+status label while running with no summary yet", () => {
    expect(deriveTitle(task({ status: "running", summary: undefined }))).toBe("assistant is working…");
  });

  it("falls back to a short task id as a last resort", () => {
    expect(deriveTitle(task({ status: "done", summary: undefined, taskId: "abcdef1234567890" }))).toBe("Task abcdef12");
  });

  it("labels blocked/needs-human by their actual status, not \"Task failed\" — regression: core sets .error to a session-busy message for status=\"blocked\" (deriveTaskStatus in packages/core/src/tools.ts), which used to make deriveTitle key off .error truthiness and mislabel it as failed; caught by browser smoke test, not by the unit suite, because no prior fixture combined a non-failed status with a truthy .error", () => {
    expect(deriveTitle(task({ status: "blocked", summary: undefined, error: "session busy" }))).toBe("Blocked");
    expect(deriveTitle(task({ status: "needs-human", summary: undefined, error: "needs input" }))).toBe("Needs your input");
    expect(deriveTitle(task({ status: "failed", summary: undefined, error: "boom" }))).toBe("Task failed");
  });

  it("uses a markdown summary's own heading as the title rather than showing literal ## / ** syntax — caught in a browser screenshot once summaries began rendering as real markdown", () => {
    const summary = "## What changed\n\nReworked the reconnect path. The **stale jobId** was the root cause; see `resolveJob()`.";
    expect(deriveTitle(task({ status: "done", summary }))).toBe("What changed");
  });

  it("strips inline markdown from a summary with no heading, without cutting a hard-wrapped one at its first newline", () => {
    expect(deriveTitle(task({ status: "done", summary: "Fixed the **stale** `jobId`\nand added coverage." }))).toBe(
      "Fixed the stale jobId and added coverage.",
    );
    expect(deriveTitle(task({ status: "done", summary: "See [the PR](https://x/pull/1) for details." }))).toBe("See the PR for details.");
    expect(deriveTitle(task({ status: "done", summary: "- shipped it" }))).toBe("shipped it");
  });

  it("never references the stored prompt field — the function signature doesn't even accept one", () => {
    // Structural guarantee: deriveTitle takes a task/snapshot, which per the
    // core contract never carries a `prompt` field (see getTaskPrompt's
    // separate return type in packages/core/src/types.ts). Passing one in
    // anyway must not leak into the title.
    const withPrompt = task({ status: "done", summary: undefined, prompt: { task: "the real secret ask" } });
    expect(deriveTitle(withPrompt)).not.toContain("secret");
  });
});

