describe("mergePinnedDetail — regression coverage for the browser-smoke-caught bug", () => {
  // Deliberately TaskSummary-shaped fixtures (no `artifacts` field) — the
  // same shape a real list_tasks/get_session(mode:"tasks") call returns
  // (see packages/core/src/tools.ts's listTasks(), which never includes
  // artifacts). A fixture that accidentally carries artifacts on a
  // "non-pinned" task would hide exactly the bug this covers, the same way
  // an over-generous browser-harness mock did during manual verification.
  function summary(overrides = {}) {
    return { taskId: "s-task", jobId: "s-task", sessionKey: "s-1", agent: "assistant", status: "done", startedAt: 1, lastEventAt: 2, summary: "plain summary", ...overrides };
  }

  it("returns the list unchanged when there's no pinned detail yet", () => {
    const tasks = [summary()];
    expect(mergePinnedDetail(tasks, null)).toBe(tasks);
  });

  it("merges the full snapshot only into the task matching pinnedDetail's id — every other task stays a plain summary", () => {
    const pinned = summary({ taskId: "s-task", jobId: "s-task", artifacts: { prUrl: "https://x/pull/1", branchName: "fix/x" }, updates: [{ ts: 1, type: "tool", text: "did a thing" }] });
    const other = summary({ taskId: "other-task", jobId: "other-task", sessionKey: "s-2" });
    const merged = mergePinnedDetail([pinned, other], pinned);

    expect(merged[0].artifacts).toEqual({ prUrl: "https://x/pull/1", branchName: "fix/x" });
    expect(deriveTitle(merged[0])).toBe("PR: fix/x");

    // The regression itself: a non-pinned task must never pick up artifacts
    // it was never fetched with, and its title must stay summary-derived.
    expect(merged[1]).not.toHaveProperty("artifacts");
    expect(deriveTitle(merged[1])).toBe("plain summary");
  });

  it("matches by id across taskId/jobId naming (get_task uses taskId, list_tasks/get_session also expose jobId)", () => {
    const pinned = { jobId: "job-1", sessionKey: "s-1", status: "done", agent: "assistant", startedAt: 1, lastEventAt: 2, artifacts: { prUrl: "https://x/pull/2" } };
    const listEntry = summary({ taskId: "job-1", jobId: "job-1" });
    expect(mergePinnedDetail([listEntry], pinned)[0].artifacts).toBeDefined();
  });
});

describe("ensurePinnedTask — the pinned task survives dropping out of list_tasks(view:\"active\")", () => {
  it("merges, exactly like mergePinnedDetail, when the pinned task is still in the list", () => {
    const pinned = { taskId: "task-1", jobId: "task-1", sessionKey: "session-1", status: "running", startedAt: 1, lastEventAt: 9, artifacts: { prUrl: "https://x/pull/1" } };
    const result = ensurePinnedTask([task(), task({ taskId: "task-2", jobId: "task-2" })], pinned);
    expect(result).toHaveLength(2);
    expect(result[0].artifacts).toEqual({ prUrl: "https://x/pull/1" });
    expect(result[1].artifacts).toBeUndefined();
  });

  it("adds the pinned task when list_tasks has dropped it — a completed task must not vanish", () => {
    // The exact production sequence: the focused task completes, so the next
    // list_tasks(view:"active") no longer returns it. Merging alone would
    // silently render the user's just-finished task as gone.
    const finished = { taskId: "task-1", jobId: "task-1", sessionKey: "session-1", status: "done", agent: "assistant", startedAt: 1, lastEventAt: 9, summary: "Shipped it." };
    const activeOnly = [task({ taskId: "task-2", jobId: "task-2", sessionKey: "session-2" })];
    const result = ensurePinnedTask(activeOnly, finished);
    expect(result).toHaveLength(2);
    expect(result.find((t) => t.taskId === "task-1")).toEqual(finished);
  });

  it("is a no-op without a pinned detail, or when the pinned detail has no resolvable id", () => {
    const tasks = [task()];
    expect(ensurePinnedTask(tasks, null)).toBe(tasks);
    expect(ensurePinnedTask(tasks, { sessionKey: "session-1", status: "done" })).toBe(tasks);
  });

  it("never mutates the input list", () => {
    const tasks = [task()];
    ensurePinnedTask(tasks, { taskId: "other", jobId: "other", sessionKey: "s", status: "done", lastEventAt: 3 });
    expect(tasks).toHaveLength(1);
  });
});

